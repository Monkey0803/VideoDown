#!/usr/bin/env python3
"""Convert the checked-in Shiying SVG kit to Android vectors using only the stdlib."""

from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs/design/shiying-icons"
OUTPUT = ROOT / "app/src/main/res/drawable"
ANDROID = "http://schemas.android.com/apk/res/android"


def number(value: float) -> str:
    return f"{value:g}"


def shape_path(element: ET.Element) -> str:
    tag = element.tag.split("}")[-1]
    attrs = element.attrib
    if tag == "path":
        return attrs["d"]
    if tag in ("circle", "ellipse"):
        cx, cy = float(attrs["cx"]), float(attrs["cy"])
        rx = float(attrs.get("rx", attrs.get("r", "0")))
        ry = float(attrs.get("ry", attrs.get("r", "0")))
        return f"M{number(cx-rx)},{number(cy)}a{number(rx)},{number(ry)} 0,1 0,{number(2*rx)},0a{number(rx)},{number(ry)} 0,1 0,{number(-2*rx)},0Z"
    if tag == "rect":
        x, y = float(attrs.get("x", 0)), float(attrs.get("y", 0))
        w, h = float(attrs["width"]), float(attrs["height"])
        rx = min(float(attrs.get("rx", 0)), w / 2)
        ry = min(float(attrs.get("ry", attrs.get("rx", 0))), h / 2)
        if not rx or not ry:
            return f"M{number(x)},{number(y)}h{number(w)}v{number(h)}h{number(-w)}Z"
        return (f"M{number(x+rx)},{number(y)}H{number(x+w-rx)}"
                f"a{number(rx)},{number(ry)} 0,0 1,{number(rx)},{number(ry)}V{number(y+h-ry)}"
                f"a{number(rx)},{number(ry)} 0,0 1,{number(-rx)},{number(ry)}H{number(x+rx)}"
                f"a{number(rx)},{number(ry)} 0,0 1,{number(-rx)},{number(-ry)}V{number(y+ry)}"
                f"a{number(rx)},{number(ry)} 0,0 1,{number(rx)},{number(-ry)}Z")
    raise ValueError(f"Unsupported SVG shape: {tag}")


def convert(source: Path, target: Path, mirrored: bool = False) -> None:
    svg = ET.parse(source).getroot()
    viewport = svg.attrib["viewBox"].split()
    if viewport[:2] != ["0", "0"]:
        raise ValueError("Expected a zero-origin SVG viewport")
    width, height = viewport[2:]
    vector = ET.Element("vector", {
        "xmlns:android": ANDROID,
        "android:width": width + "dp", "android:height": height + "dp",
        "android:viewportWidth": width, "android:viewportHeight": height,
    })
    if mirrored:
        vector.set("android:autoMirrored", "true")

    def visit(element: ET.Element, inherited: dict[str, str]) -> None:
        attrs = inherited | element.attrib
        tag = element.tag.split("}")[-1]
        if tag == "title":
            return
        if tag in ("svg", "g"):
            for child in element:
                visit(child, attrs)
            return
        path = ET.SubElement(vector, "path", {"android:pathData": shape_path(element)})
        for svg_attr, android_attr in (("fill", "fillColor"), ("stroke", "strokeColor")):
            color = attrs.get(svg_attr, "black" if svg_attr == "fill" else "none")
            if color != "none":
                if color == "currentColor":
                    color = attrs.get("color", "#FFFFFF")
                if color.startswith("var("):
                    raise ValueError(f"Unresolved CSS color in {source}")
                path.set("android:" + android_attr, color)
        if attrs.get("stroke", "none") != "none":
            path.set("android:strokeWidth", attrs.get("stroke-width", "1"))
            path.set("android:strokeLineCap", attrs.get("stroke-linecap", "butt"))
            path.set("android:strokeLineJoin", attrs.get("stroke-linejoin", "miter"))

    # Use a transparent play cutout instead of the SVG's theme-dependent inner fill.
    if source.name == "library-selected.svg":
        ET.SubElement(vector, "path", {
            "android:pathData": "M6,3H18", "android:strokeColor": "#FFFFFF",
            "android:strokeWidth": "2", "android:strokeLineCap": "round",
        })
        ET.SubElement(vector, "path", {
            "android:pathData": "M6,7H18a3,3 0,0 1,3,3V18a3,3 0,0 1,-3,3H6a3,3 0,0 1,-3,-3V10a3,3 0,0 1,3,-3Z M10,11L15,14L10,17Z",
            "android:fillColor": "#FFFFFF", "android:fillType": "evenOdd",
        })
    else:
        visit(svg, {})
    ET.indent(vector)
    target.write_text('<?xml version="1.0" encoding="utf-8"?>\n'
                      f'<!-- Source: {source.relative_to(ROOT)}; generated by scripts/generate_shiying_icons.py -->\n'
                      + ET.tostring(vector, encoding="unicode") + "\n")


def main() -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for source in sorted((SOURCE / "icons").glob("*.svg")):
        convert(source, OUTPUT / ("ic_shiying_" + source.stem.replace("-", "_") + ".xml"),
                mirrored=source.stem in ("back", "forward"))
    convert(SOURCE / "brand/brand-mark-small.svg", OUTPUT / "ic_shiying_brand.xml")
    convert(SOURCE / "brand/frame-foreground.svg", OUTPUT / "ic_launcher_foreground.xml")
    convert(SOURCE / "brand/frame-monochrome.svg", OUTPUT / "ic_launcher_monochrome.xml")
    # Playback controls supplement the kit using the same grid and rounded stroke.
    for name, path in {
        "fullscreen": "M8,3H3V8M16,3H21V8M3,16V21H8M21,16V21H16",
        "fullscreen_exit": "M3,8H8V3M16,3V8H21M8,21V16H3M21,16H16V21",
    }.items():
        (OUTPUT / f"ic_shiying_{name}.xml").write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" '
            'android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n'
            f'    <path android:pathData="{path}" android:strokeColor="#FFFFFF" '
            'android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round" />\n'
            '</vector>\n')
    (OUTPUT / "ic_launcher_background.xml").write_text('''<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0H108V108H0Z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0"
                android:endX="108" android:endY="108"
                android:startColor="#FFAD75" android:endColor="#F2784B" />
        </aapt:attr>
    </path>
</vector>
''')


if __name__ == "__main__":
    main()
